//! UAX #9 — Unicode Bidirectional Algorithm (Unicode 18.0.0): paragraph level, explicit embeddings and isolates,
//! isolating run sequences, weak and neutral resolution (including paired brackets), implicit levels, line
//! level L1 and visual reordering L2.
//!
//! Spec: https://www.unicode.org/reports/tr9/ — §3.3.1 P2–P3 (paragraph level), §3.3.2 X1–X10 (explicit levels,
//! isolating run sequences), §3.3.3 W1–W7, §3.3.4 N0–N2 (BD14–BD16 bracket pairs), §3.3.5 I1–I2, §3.4 L1–L2.
//! Property data (Bidi_Class, Bidi_Paired_Bracket(_Type), canonical bracket singletons) lives in `uax9_tables.rs`,
//! generated by `tools/gen_uax9.py`. Written from the specification text.
//!
//! The line is treated as one paragraph (and one line). A B (paragraph separator) inside the input resets the
//! embedding state at that point and takes the paragraph level (X8), as the conformance data expects.

use crate::uax9_tables::{BRACKETS, BRACKET_CANON, CLASS_RUNS};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Class {
    L,
    R,
    AL,
    EN,
    ES,
    ET,
    AN,
    CS,
    NSM,
    BN,
    B,
    S,
    WS,
    ON,
    LRE,
    LRO,
    RLE,
    RLO,
    PDF,
    LRI,
    RLI,
    FSI,
    PDI,
}

const CLASS_ORDER: [Class; 23] = [
    Class::L,
    Class::R,
    Class::AL,
    Class::EN,
    Class::ES,
    Class::ET,
    Class::AN,
    Class::CS,
    Class::NSM,
    Class::BN,
    Class::B,
    Class::S,
    Class::WS,
    Class::ON,
    Class::LRE,
    Class::LRO,
    Class::RLE,
    Class::RLO,
    Class::PDF,
    Class::LRI,
    Class::RLI,
    Class::FSI,
    Class::PDI,
];

/// Bidi_Class of a code point.
pub fn class_of(c: char) -> Class {
    let cp = c as u32;
    let i = CLASS_RUNS.partition_point(|&(start, _)| start <= cp) - 1;
    CLASS_ORDER[CLASS_RUNS[i].1 as usize]
}

/// Paired-bracket data for a code point (BD14–BD16): (canonical key shared by a pair, is_closing), or None.
pub fn bracket_of(c: char) -> Option<(u32, bool)> {
    let cp = c as u32;
    let &(_, pair, is_close) = BRACKETS.iter().find(|&&(b, _, _)| b == cp)?;
    // Key both members of a pair with the canonical form of the opening bracket.
    let open = if is_close { pair } else { cp };
    let canon = BRACKET_CANON.iter().find(|&&(from, _)| from == open).map_or(open, |&(_, to)| to);
    Some((canon, is_close))
}

/// Paragraph direction requested by the caller.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Direction {
    Ltr,
    Rtl,
    /// P2–P3: from the first strong character, default LTR.
    Auto,
}

/// Result: paragraph level, the resolved level of each character (`None` for characters removed by X9),
/// and the visual order (indices of the kept characters, left to right, L2).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Resolved {
    pub para_level: u8,
    pub levels: Vec<Option<u8>>,
    pub order: Vec<usize>,
}

const MAX_DEPTH: u8 = 125;
const MAX_BRACKET_STACK: usize = 63;

fn is_removed_by_x9(c: Class) -> bool {
    matches!(c, Class::LRE | Class::RLE | Class::LRO | Class::RLO | Class::PDF | Class::BN)
}

fn is_isolate_initiator(c: Class) -> bool {
    matches!(c, Class::LRI | Class::RLI | Class::FSI)
}

fn is_neutral_or_isolate(c: Class) -> bool {
    matches!(c, Class::B | Class::S | Class::WS | Class::ON | Class::LRI | Class::RLI | Class::FSI | Class::PDI)
}

/// Matching PDI for each isolate initiator (BD9), by scanning with a depth counter.
fn matching_pdi(classes: &[Class]) -> Vec<Option<usize>> {
    let mut m = vec![None; classes.len()];
    let mut stack: Vec<usize> = Vec::new();
    for (i, &c) in classes.iter().enumerate() {
        if is_isolate_initiator(c) {
            stack.push(i);
        } else if c == Class::PDI {
            if let Some(o) = stack.pop() {
                m[o] = Some(i);
            }
        } else if c == Class::B {
            stack.clear();
        }
    }
    m
}

/// P2–P3 over `classes[from..to]`, skipping isolate contents. Returns Some(0|1) or None if no strong character.
fn first_strong_level(classes: &[Class], pdi_of: &[Option<usize>], from: usize, to: usize) -> Option<u8> {
    let mut i = from;
    while i < to {
        match classes[i] {
            Class::L => return Some(0),
            Class::R | Class::AL => return Some(1),
            c if is_isolate_initiator(c) => match pdi_of[i] {
                Some(p) => i = p,
                None => return None,
            },
            Class::B => return None,
            _ => {}
        }
        i += 1;
    }
    None
}

/// Resolve the bidi levels of a paragraph given per-character Bidi_Class and optional bracket data.
pub fn resolve(classes: &[Class], brackets: &[Option<(u32, bool)>], dir: Direction) -> Resolved {
    let n = classes.len();
    let pdi_of = matching_pdi(classes);
    let para_level: u8 = match dir {
        Direction::Ltr => 0,
        Direction::Rtl => 1,
        Direction::Auto => first_strong_level(classes, &pdi_of, 0, n).unwrap_or(0),
    };

    // X1–X8: explicit levels and directions.
    let mut level = vec![para_level; n];
    let mut ty: Vec<Class> = classes.to_vec();
    #[derive(Clone, Copy)]
    struct Entry {
        level: u8,
        ovr: Option<Class>,
        isolate: bool,
    }
    let mut stack: Vec<Entry> = vec![Entry { level: para_level, ovr: None, isolate: false }];
    let (mut overflow_iso, mut overflow_emb, mut valid_iso) = (0usize, 0usize, 0usize);
    for i in 0..n {
        let c = classes[i];
        let top = *stack.last().unwrap();
        match c {
            Class::RLE | Class::LRE | Class::RLO | Class::LRO => {
                let rtl = matches!(c, Class::RLE | Class::RLO);
                let new = if rtl { (top.level + 1) | 1 } else { (top.level + 2) & !1 };
                level[i] = top.level;
                if new <= MAX_DEPTH && overflow_iso == 0 && overflow_emb == 0 {
                    let ovr = match c {
                        Class::RLO => Some(Class::R),
                        Class::LRO => Some(Class::L),
                        _ => None,
                    };
                    stack.push(Entry { level: new, ovr, isolate: false });
                } else if overflow_iso == 0 {
                    overflow_emb += 1;
                }
            }
            Class::RLI | Class::LRI | Class::FSI => {
                level[i] = top.level;
                if let Some(o) = top.ovr {
                    ty[i] = o;
                }
                let rtl = match c {
                    Class::RLI => true,
                    Class::LRI => false,
                    _ => first_strong_level(classes, &pdi_of, i + 1, pdi_of[i].unwrap_or(n)) == Some(1),
                };
                let new = if rtl { (top.level + 1) | 1 } else { (top.level + 2) & !1 };
                if new <= MAX_DEPTH && overflow_iso == 0 && overflow_emb == 0 {
                    valid_iso += 1;
                    stack.push(Entry { level: new, ovr: None, isolate: true });
                } else {
                    overflow_iso += 1;
                }
            }
            Class::PDI => {
                if overflow_iso > 0 {
                    overflow_iso -= 1;
                } else if valid_iso > 0 {
                    overflow_emb = 0;
                    while stack.last().is_some_and(|e| !e.isolate) {
                        stack.pop();
                    }
                    stack.pop();
                    valid_iso -= 1;
                }
                let t = *stack.last().unwrap();
                level[i] = t.level;
                if let Some(o) = t.ovr {
                    ty[i] = o;
                }
            }
            Class::PDF => {
                level[i] = top.level;
                if overflow_iso > 0 {
                } else if overflow_emb > 0 {
                    overflow_emb -= 1;
                } else if !top.isolate && stack.len() >= 2 {
                    stack.pop();
                }
            }
            Class::B => {
                // X8: a paragraph separator terminates all embeddings and isolates.
                level[i] = para_level;
                stack.truncate(1);
                overflow_iso = 0;
                overflow_emb = 0;
                valid_iso = 0;
            }
            Class::BN => level[i] = top.level,
            _ => {
                level[i] = top.level;
                if let Some(o) = top.ovr {
                    ty[i] = o;
                }
            }
        }
    }

    // Explicit levels (X1–X8) are the inputs to sos/eos and to the sequence resolution below.
    let explicit = level.clone();

    // X9: the characters kept for the rest of the algorithm.
    let kept: Vec<usize> = (0..n).filter(|&i| !is_removed_by_x9(classes[i])).collect();

    // X10: level runs over kept characters, linked through isolate initiators and their matching PDI.
    let mut runs: Vec<Vec<usize>> = Vec::new(); // positions into `kept`
    {
        let mut cur: Vec<usize> = Vec::new();
        for (k, &i) in kept.iter().enumerate() {
            if let Some(&last) = cur.last() {
                if level[kept[last]] != level[i] {
                    runs.push(std::mem::take(&mut cur));
                }
            }
            cur.push(k);
        }
        if !cur.is_empty() {
            runs.push(cur);
        }
    }
    let kept_pos_of: Vec<Option<usize>> = {
        let mut v = vec![None; n];
        for (k, &i) in kept.iter().enumerate() {
            v[i] = Some(k);
        }
        v
    };
    let run_starting_at = |kpos: usize, runs: &Vec<Vec<usize>>| -> Option<usize> { runs.iter().position(|r| r[0] == kpos) };
    let mut sequences: Vec<Vec<usize>> = Vec::new(); // each a list of kept positions
    let mut consumed = vec![false; runs.len()];
    for r in 0..runs.len() {
        if consumed[r] {
            continue;
        }
        let mut seq: Vec<usize> = Vec::new();
        let mut cur = r;
        loop {
            consumed[cur] = true;
            seq.extend_from_slice(&runs[cur]);
            let last_kpos = *runs[cur].last().unwrap();
            let last = kept[last_kpos];
            if is_isolate_initiator(classes[last]) {
                if let Some(p) = pdi_of[last] {
                    if let Some(pk) = kept_pos_of[p] {
                        if let Some(next) = run_starting_at(pk, &runs) {
                            if !consumed[next] {
                                cur = next;
                                continue;
                            }
                        }
                    }
                }
            }
            break;
        }
        sequences.push(seq);
    }

    // Per-sequence resolution (W, N, I rules), writing final levels into `level`.
    for seq in &sequences {
        let first = kept[seq[0]];
        let last = kept[*seq.last().unwrap()];
        let seq_level = explicit[first];
        // sos / eos (X10): compare with the explicit levels of the neighbouring kept characters.
        let before = (0..first).rev().find(|&i| !is_removed_by_x9(classes[i])).map(|i| explicit[i]).unwrap_or(para_level);
        let after = if is_isolate_initiator(classes[last]) {
            para_level
        } else {
            (last + 1..n).find(|&i| !is_removed_by_x9(classes[i])).map(|i| explicit[i]).unwrap_or(para_level)
        };
        let sos = if seq_level.max(before) % 2 == 1 { Class::R } else { Class::L };
        let eos = if seq_level.max(after) % 2 == 1 { Class::R } else { Class::L };
        let idx: Vec<usize> = seq.iter().map(|&k| kept[k]).collect();
        let mut t: Vec<Class> = idx.iter().map(|&i| ty[i]).collect();
        let len = t.len();

        // W1: NSM takes the type of the previous character (ON after an isolate initiator or PDI).
        for k in 0..len {
            if t[k] == Class::NSM {
                t[k] = if k == 0 {
                    sos
                } else if is_isolate_initiator(t[k - 1]) || t[k - 1] == Class::PDI {
                    Class::ON
                } else {
                    t[k - 1]
                };
            }
        }
        // W2: EN after AL becomes AN; W3: AL becomes R.
        let mut last_strong = sos;
        for k in 0..len {
            match t[k] {
                Class::L | Class::R | Class::AL => last_strong = t[k],
                Class::EN if last_strong == Class::AL => t[k] = Class::AN,
                _ => {}
            }
        }
        for c in t.iter_mut() {
            if *c == Class::AL {
                *c = Class::R;
            }
        }
        // W4: single separators between numbers.
        for k in 1..len.saturating_sub(1) {
            let (p, nx) = (t[k - 1], t[k + 1]);
            if t[k] == Class::ES && p == Class::EN && nx == Class::EN {
                t[k] = Class::EN;
            } else if t[k] == Class::CS && p == nx && (p == Class::EN || p == Class::AN) {
                t[k] = p;
            }
        }
        // W5: ET sequences adjacent to EN become EN.
        let mut k = 0;
        while k < len {
            if t[k] == Class::ET {
                let s = k;
                while k < len && t[k] == Class::ET {
                    k += 1;
                }
                let adj_en = (s > 0 && t[s - 1] == Class::EN) || (k < len && t[k] == Class::EN);
                if adj_en {
                    for c in &mut t[s..k] {
                        *c = Class::EN;
                    }
                }
            } else {
                k += 1;
            }
        }
        // W6: remaining separators and terminators become ON.
        for c in t.iter_mut() {
            if matches!(*c, Class::ES | Class::ET | Class::CS) {
                *c = Class::ON;
            }
        }
        // W7: EN preceded by L (or sos L) becomes L.
        let mut last_strong = sos;
        for c in t.iter_mut() {
            match *c {
                Class::L | Class::R => last_strong = *c,
                Class::EN if last_strong == Class::L => *c = Class::L,
                _ => {}
            }
        }

        // N0: paired brackets (BD16), using the current types and the embedding direction.
        let embed = if seq_level % 2 == 1 { Class::R } else { Class::L };
        let mut pairs: Vec<(usize, usize)> = Vec::new();
        {
            let mut stack: Vec<(u32, usize)> = Vec::new();
            for k in 0..len {
                let i = idx[k];
                if t[k] != Class::ON {
                    continue;
                }
                if let Some((key, is_close)) = brackets.get(i).copied().flatten() {
                    if !is_close {
                        if stack.len() == MAX_BRACKET_STACK {
                            break;
                        }
                        stack.push((key, k));
                    } else if let Some(pos) = stack.iter().rposition(|&(open_key, _)| open_key == key) {
                        let (_, open_k) = stack[pos];
                        stack.truncate(pos);
                        pairs.push((open_k, k));
                    }
                }
            }
            pairs.sort();
        }
        let strong_of = |c: Class| -> Option<Class> {
            match c {
                Class::L => Some(Class::L),
                Class::R | Class::AN | Class::EN => Some(Class::R),
                _ => None,
            }
        };
        for (o, c) in pairs {
            let mut found_embed = false;
            let mut found_opposite = false;
            for &x in &t[o + 1..c] {
                match strong_of(x) {
                    Some(d) if d == embed => found_embed = true,
                    Some(_) => found_opposite = true,
                    None => {}
                }
            }
            let resolved = if found_embed {
                Some(embed)
            } else if found_opposite {
                // Context before the opening bracket decides (N0 c.2).
                let mut ctx = sos;
                for x in (0..o).rev() {
                    if let Some(d) = strong_of(t[x]) {
                        ctx = d;
                        break;
                    }
                }
                let opposite = if embed == Class::L { Class::R } else { Class::L };
                Some(if ctx == opposite { opposite } else { embed })
            } else {
                None
            };
            if let Some(d) = resolved {
                for &pos in &[o, c] {
                    t[pos] = d;
                    // NSMs that followed a bracket take its new type (N0 note).
                    let mut j = pos + 1;
                    while j < len && classes[idx[j]] == Class::NSM {
                        t[j] = d;
                        j += 1;
                    }
                }
            }
        }

        // N1–N2: neutral and isolate sequences.
        let mut k = 0;
        while k < len {
            if is_neutral_or_isolate(t[k]) {
                let s = k;
                while k < len && is_neutral_or_isolate(t[k]) {
                    k += 1;
                }
                let before_t = if s == 0 { sos } else { strong_of(t[s - 1]).unwrap_or(embed) };
                let after_t = if k == len { eos } else { strong_of(t[k]).unwrap_or(embed) };
                let d = if before_t == after_t { before_t } else { embed };
                for c in &mut t[s..k] {
                    *c = d;
                }
            } else {
                k += 1;
            }
        }

        // I1–I2: implicit levels.
        for (k, &i) in idx.iter().enumerate() {
            let base = explicit[i];
            level[i] = match (base % 2 == 0, t[k]) {
                (true, Class::R) => base + 1,
                (true, Class::AN | Class::EN) => base + 2,
                (false, Class::L | Class::EN | Class::AN) => base + 1,
                _ => base,
            };
        }
    }

    // L1: reset separators and trailing whitespace (by original class) to the paragraph level.
    let mut trailing = true;
    for i in (0..n).rev() {
        let c = classes[i];
        if c == Class::B || c == Class::S {
            level[i] = para_level;
            trailing = true;
        } else if trailing && (c == Class::WS || is_isolate_initiator(c) || c == Class::PDI || is_removed_by_x9(c)) {
            level[i] = para_level;
        } else {
            trailing = false;
        }
    }
    // Removed characters carry no level in the output.
    let levels: Vec<Option<u8>> = (0..n).map(|i| if is_removed_by_x9(classes[i]) { None } else { Some(level[i]) }).collect();

    // L2: visual order of the kept characters.
    let mut order: Vec<usize> = (0..n).filter(|&i| levels[i].is_some()).collect();
    let mut lv: Vec<u8> = order.iter().map(|&i| levels[i].unwrap()).collect();
    let max = lv.iter().copied().max().unwrap_or(0);
    // Lowest odd level: the smallest of (level | 1) over the line.
    let min_odd = lv.iter().map(|&l| l | 1).min().unwrap_or(1);
    let mut lvl = max;
    while lvl >= min_odd {
        let mut s = 0;
        while s < order.len() {
            if lv[s] >= lvl {
                let mut e = s;
                while e < order.len() && lv[e] >= lvl {
                    e += 1;
                }
                order[s..e].reverse();
                lv[s..e].reverse();
                s = e;
            } else {
                s += 1;
            }
        }
        lvl -= 1;
    }
    Resolved { para_level, levels, order }
}

/// Convenience: resolve a string (classes from the UCD, brackets from BidiBrackets.txt).
pub fn resolve_str(text: &str, dir: Direction) -> Resolved {
    let chars: Vec<char> = text.chars().collect();
    let classes: Vec<Class> = chars.iter().map(|&c| class_of(c)).collect();
    let brackets: Vec<Option<(u32, bool)>> = chars.iter().map(|&c| bracket_of(c)).collect();
    resolve(&classes, &brackets, dir)
}
