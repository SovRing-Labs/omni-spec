#!/usr/bin/env python3
"""Generate brotli static tables from the RFC text (tests/data/rfc7932.txt, RFC 7932, Alakuijala & Szabadka, 2016).

Outputs:
  src/brotli_dict.bin     static dictionary DICT (RFC 7932 Appendix A), 122,784 bytes
  src/brotli_tables.rs    LUT0/LUT1/LUT2 (§7.1), NDBITS (Appendix A), TRANSFORMS (Appendix B)

Every extracted table is checked against the RFC's own length and CRC-32 values before it is written:
  DICT: 122,784 bytes, CRC-32 0x5136cb04; transform byte sequence: 648 bytes, CRC-32 0x3d965f81.
Usage: python3 tools/gen_brotli_tables.py
"""
import os
import re
import sys
import zlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RFC = os.path.join(ROOT, "tests", "data", "rfc7932.txt")
DICT_OUT = os.path.join(ROOT, "src", "brotli_dict.bin")
RS_OUT = os.path.join(ROOT, "src", "brotli_tables.rs")


def section(lines, start_pat, end_pat):
    s = next(i for i, l in enumerate(lines) if re.match(start_pat, l))
    e = next(i for i in range(s + 1, len(lines)) if re.match(end_pat, lines[i]))
    return lines[s + 1:e]


def lut(lines, name):
    s = next(i for i, l in enumerate(lines) if l.strip() == f"{name} :=")
    vals = []
    for l in lines[s + 1:]:
        if not l.strip():
            if vals:
                break
            continue
        if not re.fullmatch(r"\s*\d+(\s*,\s*\d+)*,?\s*", l):
            break
        vals += [int(x) for x in re.findall(r"\d+", l)]
        if len(vals) >= 256:
            break
    assert len(vals) == 256, f"{name}: {len(vals)} values"
    return vals


def c_string(lit):
    """Decode a C string literal (only \\\\, \\\", \\' escapes occur in Appendix B)."""
    body = lit[1:-1]
    out, i = [], 0
    while i < len(body):
        if body[i] == "\\" and body[i + 1] == "x":
            out.append(chr(int(body[i + 2:i + 4], 16)))
            i += 4
        elif body[i] == "\\":
            out.append({"\\": "\\", '"': '"', "'": "'", "n": "\n", "t": "\t"}[body[i + 1]])
            i += 2
        else:
            out.append(body[i])
            i += 1
    return "".join(out).encode("latin-1")


def main():
    lines = open(RFC, encoding="utf-8").read().split("\n")

    # Appendix A: DICT hex dump.
    a = section(lines, r"^Appendix A\.", r"^Appendix B\.")
    hexdigits = "".join(re.findall(r"[0-9a-f]+", "".join(l for l in a if re.fullmatch(r"\s+[0-9a-f]+\s*", l))))
    dic = bytes.fromhex(hexdigits)
    assert len(dic) == 122784, len(dic)
    assert zlib.crc32(dic) == 0x5136CB04, hex(zlib.crc32(dic))
    ndbits_line = next(i for i, l in enumerate(a) if "NDBITS :=" in l)
    ndbits = [int(x) for x in re.findall(r"\d+", a[ndbits_line].split(":=", 1)[1] + " " + " ".join(a[ndbits_line + 1:ndbits_line + 3]))]
    assert len(ndbits) == 25, ndbits

    # Appendix B: transforms (ID, prefix, elementary transform, suffix).
    b = section(lines, r"^Appendix B\.", r"^Appendix C\.")
    rows = {}
    kinds = {"Identity": 0, "FermentFirst": 1, "FermentAll": 2}
    for l in b:
        m = re.match(r'^\s*(\d+)\s+("(?:[^"\\]|\\.)*")\s+(\w+)\s+("(?:[^"\\]|\\.)*")\s*$', l)
        if m:
            tid = int(m.group(1))
            name = m.group(3)
            if name in kinds:
                kind = kinds[name]
            elif name.startswith("OmitFirst"):
                kind = 2 + int(name[len("OmitFirst"):])
            elif name.startswith("OmitLast"):
                kind = 11 + int(name[len("OmitLast"):])
            else:
                raise SystemExit(f"unknown transform {name}")
            rows[tid] = (c_string(m.group(2)), kind, c_string(m.group(4)))
    assert sorted(rows) == list(range(121)), len(rows)
    seq = b"".join(rows[i][0] + b"\x00" + bytes([rows[i][1]]) + rows[i][2] + b"\x00" for i in range(121))
    assert len(seq) == 648, len(seq)
    assert zlib.crc32(seq) == 0x3D965F81, hex(zlib.crc32(seq))

    luts = {n: lut(lines, n) for n in ("Lut0", "Lut1", "Lut2")}
    # RFC 7932 §7.1 gives a CRC-32 per table; check every table against it.
    for n, want in (("Lut0", 0x8E91EFB7), ("Lut1", 0xD01A32F4), ("Lut2", 0x0DD7A0D6)):
        got = zlib.crc32(bytes(luts[n]))
        assert got == want, (n, hex(got))

    with open(DICT_OUT, "wb") as f:
        f.write(dic)
    out = ["// @generated by tools/gen_brotli_tables.py from tests/data/rfc7932.txt (RFC 7932). Do not hand-edit.",
           "// Each table was checked against the RFC's own length and CRC-32 before generation.", ""]
    for n, v in luts.items():
        out.append(f"/// {n} (RFC 7932 §7.1).")
        out.append(f"pub(crate) static {n.upper()}: [u8; 256] = [")
        for i in range(0, 256, 16):
            out.append("    " + ", ".join(str(x) for x in v[i:i + 16]) + ",")
        out.append("];")
        out.append("")
    out.append("/// NDBITS[length] (RFC 7932 Appendix A): bit depth of the word index for each length.")
    out.append("pub(crate) static NDBITS: [u8; 25] = [" + ", ".join(str(x) for x in ndbits) + "];")
    out.append("")
    out.append("/// Transforms 0..=120 (RFC 7932 Appendix B): (prefix, kind, suffix). Kind: 0 Identity, 1 FermentFirst,")
    out.append("/// 2 FermentAll, 3..=11 OmitFirst1..9, 12..=20 OmitLast1..9 (the RFC's transform byte values).")
    out.append("pub(crate) static TRANSFORMS: [(&[u8], u8, &[u8]); 121] = [")
    for i in range(121):
        p, k, s = rows[i]
        out.append(f"    ({rust_bytes(p)}, {k}, {rust_bytes(s)}),")
    out.append("];")
    with open(RS_OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {DICT_OUT} ({len(dic)} bytes) and {RS_OUT}", file=sys.stderr)


def rust_bytes(b):
    return 'b"' + "".join(chr(c) if 32 <= c < 127 and c not in (34, 92) else f"\\x{c:02x}" for c in b) + '"'


if __name__ == "__main__":
    main()
