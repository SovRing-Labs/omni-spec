#!/usr/bin/env python3
"""Generate src/html_entities.rs from tests/data/html-entities.json (WHATWG HTML §13.5, entities.json).

Keys are as published ('&amp;' and 'amp;' both appear). Output: NAMED: &[(&str, &[u32])], sorted by name, the
name written without the leading '&' and including a trailing ';' as published.
Usage: python3 tools/gen_html_entities.py
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "tests", "data", "html-entities.json")
OUT = os.path.join(ROOT, "src", "html_entities.rs")


def main():
    d = json.load(open(SRC, encoding="utf-8"))
    items = sorted((k[1:], v["codepoints"]) for k, v in d.items())
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// @generated by tools/gen_html_entities.py from tests/data/html-entities.json (WHATWG HTML §13.5).\n")
        f.write("// Do not hand-edit.\n\n")
        f.write("/// Named character references: name without '&' (with ';' where published), code points.\n")
        f.write("pub(crate) static NAMED: &[(&str, &[u32])] = &[\n")
        for name, cps in items:
            f.write(f'    ("{name}", &[{", ".join(hex(c) for c in cps)}]),\n')
        f.write("];\n")
    print(f"wrote {OUT}: {len(items)} entries")


if __name__ == "__main__":
    main()
