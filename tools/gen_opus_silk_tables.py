#!/usr/bin/env python3
"""Generate src/opus_silk_tables.rs from the TEXT of RFC 6716 §4.2 (SILK) — every table is read from the RFC's own tables by
caption, so nothing is hand-typed. Usage: gen_opus_silk_tables.py <rfc6716 .text.txt> > src/opus_silk_tables.rs"""
import re, sys

lines = open(sys.argv[1], encoding="utf-8").read().split("\n")
# drop page-break lines so tables split across pages read as one
lines = [l for l in lines if not l.startswith("Valin, et al.") and not l.startswith("RFC 6716 ")]
cap = {}
for i, l in enumerate(lines):
    m = re.match(r"^Table (\d+):", l)
    if m: cap.setdefault(int(m.group(1)), i)

def body(n):
    """the table rows (lines starting with '|') between table n-1's caption and table n's caption, last contiguous table only"""
    end = cap[n]
    start = cap.get(n - 1, end - 400)
    rows = [l for l in lines[start + 1:end] if l.startswith("|") or l.startswith("+")]
    # keep from the LAST top border run: find the last '+---' that starts a table (followed by header) — tables here are single
    return [l for l in rows if l.startswith("|")]

def pdfs(n):
    """all {..}/256 (or /ft) PDFs of table n, in reading order; cells may wrap over lines"""
    rows = [cells(l) for l in body(n)]
    col = next((c.index("PDF") for c in rows if "PDF" in c), None)  # the PDF column (header cell "PDF"); wrapped cells join
    text = " ".join((c[col] if col is not None and col < len(c) else " ".join(c)) for c in rows)
    out = []
    for m in re.finditer(r"\{([^}]*)\}/(\d+)", text):
        v = [int(x) for x in m.group(1).replace(" ", "").split(",") if x != ""]
        assert sum(v) == int(m.group(2)), (n, v, m.group(2))
        out.append(v)
    return out

def cells(l):
    return [c.strip() for c in l.strip().strip("|").split("|")]

def rows_numeric(n, skip_header=True):
    """rows of integers: first cell = index (or label), rest = numbers split on spaces"""
    out = []
    for l in body(n):
        c = cells(l)
        if not c or not re.fullmatch(r"-?\d+", c[0] or "x"): continue
        nums = []
        for x in c[1:]:
            nums += [int(t) for t in x.split()] if x else [None]
        out.append((int(c[0]), nums))
    return out

def rows_letters(n):
    out = []
    for l in body(n):
        c = cells(l)
        if len(c) < 2 or not c[1] or not re.fullmatch(r"([a-pA-D] ?)+", c[1]): continue
        out.append(c[1].split())
    return out

def emit(name, ty, vals):
    print(f"pub const {name}: {ty} = {vals};")

def rs(v):
    if isinstance(v, list): return "[" + ", ".join(rs(x) for x in v) + "]"
    return str(v)

def icdf(p):
    """RFC 4.1.3.3: icdf[k] = ft - fh[k]; we keep PDFs as frequency lists and decode them with RangeDecoder::pdf"""
    return p

print("//! GENERATED by tools/gen_opus_silk_tables.py from the text of RFC 6716 §4.2 (tables cited by number). Do not edit.")
print("#![allow(dead_code)]")
def pdf_const(name, n, idx=None, expect=None):
    p = pdfs(n)
    if expect is not None: assert len(p) == expect, (n, len(p))
    if idx is not None: p = p[idx]
    if isinstance(p[0], list):
        print(f"/// Table {n}")
        print(f"pub const {name}: &[&[u16]] = &[" + ", ".join("&" + rs(x) for x in p) + "];")
    else:
        print(f"/// Table {n}")
        print(f"pub const {name}: &[u16] = &{rs(p)};")

pdf_const("LBRR_FLAGS", 4, expect=2)
pdf_const("STEREO_W", 6, expect=3)
pdf_const("MID_ONLY", 8, 0, expect=1)
pdf_const("FRAME_TYPE", 9, expect=2)
pdf_const("GAIN_MSB", 11, expect=3)
pdf_const("GAIN_LSB", 12, 0, expect=1)
pdf_const("GAIN_DELTA", 13, 0, expect=1)
pdf_const("LSF_S1", 14, expect=4)
pdf_const("LSF_S2_NB", 15, expect=8)
pdf_const("LSF_S2_WB", 16, expect=8)
pdf_const("LSF_EXT", 19, 0, expect=1)
pdf_const("LSF_INTERP", 26, 0, expect=1)
pdf_const("LAG_HIGH", 29, 0, expect=1)
pdf_const("LAG_LOW", 30, expect=3)
pdf_const("LAG_DELTA", 31, 0, expect=1)
pdf_const("CONTOUR", 32, expect=4)
pdf_const("PERIODICITY", 37, 0, expect=1)
pdf_const("LTP_FILTER", 38, expect=3)
pdf_const("LTP_SCALE", 42, 0, expect=1)
pdf_const("LCG_SEED", 43, 0, expect=1)
pdf_const("RATE_LEVEL", 45, expect=2)
pdf_const("PULSE_COUNT", 46, expect=11)
for t in (47, 48, 49, 50):
    pdf_const(f"SPLIT_{ {47: 16, 48: 8, 49: 4, 50: 2}[t] }", t, expect=16)
pdf_const("LSB", 51, 0, expect=1)
pdf_const("SIGN", 52, expect=42)

w = [r[1][0] for r in rows_numeric(7)]; assert len(w) == 16
print("/// Table 7"); emit("STEREO_WEIGHTS_Q13", "[i32; 16]", rs(w))

def letters(n, rows, cols, base):
    m = rows_letters(n); assert len(m) == rows and all(len(r) == cols for r in m), (n, len(m), [len(r) for r in m])
    return [[ord(c) - ord(base) for c in r] for r in m]
print("/// Table 17 (a..h → 0..7)"); emit("LSF_S2_SEL_NB", "[[u8; 10]; 32]", rs(letters(17, 32, 10, "a")))
print("/// Table 18 (i..p → 0..7)"); emit("LSF_S2_SEL_WB", "[[u8; 16]; 32]", rs(letters(18, 32, 16, "i")))
print("/// Table 21 (A/B → 0/1)"); emit("LSF_PRED_SEL_NB", "[[u8; 9]; 32]", rs(letters(21, 32, 9, "A")))
print("/// Table 22 (C/D → 0/1)"); emit("LSF_PRED_SEL_WB", "[[u8; 15]; 32]", rs(letters(22, 32, 15, "C")))

r20 = rows_numeric(20)
A = [r[1][0] for r in r20 if r[1][0] is not None]; B = [r[1][1] for r in r20 if r[1][1] is not None]
C = [r[1][2] for r in r20]; D = [r[1][3] for r in r20]
assert len(A) == 9 and len(B) == 9 and len(C) == 15 and len(D) == 15, (A, B, C, D)
print("/// Table 20: [list A, list B] for NB/MB, [list C, list D] for WB (Q8)")
emit("LSF_PRED_NB", "[[i32; 9]; 2]", rs([A, B])); emit("LSF_PRED_WB", "[[i32; 15]; 2]", rs([C, D]))

cb23 = [r[1] for r in rows_numeric(23)]; assert len(cb23) == 32 and all(len(r) == 10 for r in cb23)
cb24 = [r[1] for r in rows_numeric(24)]; assert len(cb24) == 32 and all(len(r) == 16 for r in cb24)
print("/// Table 23"); emit("LSF_CB1_NB", "[[i32; 10]; 32]", rs(cb23))
print("/// Table 24"); emit("LSF_CB1_WB", "[[i32; 16]; 32]", rs(cb24))

r25 = rows_numeric(25)
nb = [r[1][0] for r in r25 if r[1][0] is not None]; wb = [r[1][1] for r in r25]
assert len(nb) == 11 and len(wb) == 17
print("/// Table 25"); emit("LSF_MIN_SPACING_NB", "[i32; 11]", rs(nb)); emit("LSF_MIN_SPACING_WB", "[i32; 17]", rs(wb))

r27 = rows_numeric(27)
onb = [r[1][0] for r in r27 if r[1][0] is not None]; owb = [r[1][1] for r in r27]
assert len(onb) == 10 and len(owb) == 16
print("/// Table 27"); emit("LSF_ORDER_NB", "[usize; 10]", rs(onb)); emit("LSF_ORDER_WB", "[usize; 16]", rs(owb))

cos = []
for i, v in rows_numeric(28): cos += [x for x in v if x is not None]
assert len(cos) == 129, len(cos)
print("/// Table 28"); emit("COS_Q12", "[i32; 129]", rs(cos))

for n, name, k, cnt in ((33, "CONTOUR_NB_10", 2, 3), (34, "CONTOUR_NB_20", 4, 11), (35, "CONTOUR_WB_10", 2, 12), (36, "CONTOUR_WB_20", 4, 34)):
    v = [r[1] for r in rows_numeric(n)]; assert len(v) == cnt and all(len(r) == k for r in v), n
    print(f"/// Table {n}"); emit(name, f"[[i32; {k}]; {cnt}]", rs(v))
for n, name, cnt in ((39, "LTP_TAPS_0", 8), (40, "LTP_TAPS_1", 16), (41, "LTP_TAPS_2", 32)):
    v = [r[1] for r in rows_numeric(n)]; assert len(v) == cnt and all(len(r) == 5 for r in v), n
    print(f"/// Table {n}"); emit(name, f"[[i32; 5]; {cnt}]", rs(v))
