#!/usr/bin/env python3
"""Generate src/uax29_tables.rs from the UCD files in tests/data/ (Unicode 18.0.0).

Sources:
  GraphemeBreakProperty.txt   Grapheme_Cluster_Break (UAX #29 §3.1, Table 2)
  DerivedCoreProperties.txt   Indic_Conjunct_Break (InCB; UAX #29 GB9c)
  emoji-data.txt              Extended_Pictographic (UAX #29 GB11)

Packed value: bits 0-3 GCB index (GCB_NAMES order), bits 4-5 InCB (0 None, 1 Linker, 2 Consonant, 3 Extend),
bit 6 Extended_Pictographic. Usage: python3 tools/gen_uax29.py   (from the omni-spec crate root)
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DATA = os.path.join(ROOT, "tests", "data")
OUT = os.path.join(ROOT, "src", "uax29_tables.rs")
MAX_CP = 0x110000
GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark",
       "L", "V", "T", "LV", "LVT"]
GCB_IDX = {n: i for i, n in enumerate(GCB)}
INCB = {"None": 0, "Linker": 1, "Consonant": 2, "Extend": 3}


def parse(path):
    """Return (missing, rows): @missing defaults and (lo, hi, value) from 'XXXX[..YYYY] ; value # ...' lines."""
    rows, missing = [], []
    with open(path, encoding="utf-8") as f:
        for raw in f:
            if raw.startswith("# @missing:"):
                parts = raw.split(":", 1)[1].split(";")
                lo, hi = parts[0].strip().split("..")
                missing.append((int(lo, 16), int(hi, 16), parts[1].strip()))
                continue
            line = raw.split("#", 1)[0].strip()
            if not line or ";" not in line:
                continue
            rng, val = [c.strip() for c in line.split(";")[:2]]
            lo, hi = (rng.split("..") + [rng])[:2]
            rows.append((int(lo, 16), int(hi, 16), val))
    return missing, rows


def main():
    gcb = ["Other"] * MAX_CP
    m, rows = parse(os.path.join(DATA, "GraphemeBreakProperty.txt"))
    for lo, hi, v in m + rows:
        for cp in range(lo, hi + 1):
            gcb[cp] = v
    incb = [0] * MAX_CP
    with open(os.path.join(DATA, "DerivedCoreProperties.txt"), encoding="utf-8") as f:
        for raw in f:
            if "; InCB;" not in raw or raw.startswith("#"):
                continue
            body = raw.split("#", 1)[0]
            rng, _, val = [c.strip() for c in body.split(";")[:3]]
            lo, hi = (rng.split("..") + [rng])[:2]
            for cp in range(int(lo, 16), int(hi, 16) + 1):
                incb[cp] = INCB[val]
    ext = bytearray(MAX_CP)
    with open(os.path.join(DATA, "emoji-data.txt"), encoding="utf-8") as f:
        for raw in f:
            if "Extended_Pictographic" not in raw or raw.startswith("#"):
                continue
            rng = raw.split(";", 1)[0].strip()
            lo, hi = (rng.split("..") + [rng])[:2]
            for cp in range(int(lo, 16), int(hi, 16) + 1):
                ext[cp] = 1
    runs, prev = [], None
    for cp in range(MAX_CP):
        packed = GCB_IDX[gcb[cp]] | (incb[cp] << 4) | (ext[cp] << 6)
        if packed != prev:
            runs.append((cp, packed))
            prev = packed
    with open(OUT, "w", encoding="utf-8") as out:
        out.write("// @generated by tools/gen_uax29.py from tests/data/{GraphemeBreakProperty,DerivedCoreProperties,emoji-data}.txt\n")
        out.write("// (Unicode 18.0.0). Do not hand-edit.\n")
        out.write("// Packed: bits 0-3 GCB index, bits 4-5 InCB (0 None, 1 Linker, 2 Consonant, 3 Extend), bit 6 Extended_Pictographic.\n\n")
        out.write("#[allow(dead_code)]\npub(crate) const GCB_NAMES: &[&str] = &[\n")
        for n in GCB:
            out.write(f'    "{n}",\n')
        out.write("];\n\n")
        out.write(f"/// {len(runs)} runs; sorted by start code point.\n")
        out.write("pub(crate) static RUNS: &[(u32, u8)] = &[\n")
        for start, packed in runs:
            out.write(f"    (0x{start:05X}, 0x{packed:02X}),\n")
        out.write("];\n")
    print(f"wrote {OUT}: {len(runs)} runs", file=sys.stderr)


if __name__ == "__main__":
    main()
