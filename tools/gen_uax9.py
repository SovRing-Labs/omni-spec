#!/usr/bin/env python3
"""Generate src/uax9_tables.rs from the UCD (Unicode 18.0.0) files in tests/data/.

Sources: extracted/DerivedBidiClass.txt (Bidi_Class for every code point, including the UCD defaults for
unassigned code points) -> saved as tests/data/DerivedBidiClass.txt; BidiBrackets.txt (Bidi_Paired_Bracket and
Bidi_Paired_Bracket_Type, UAX #9 BD14–BD16); UnicodeData.txt canonical singleton decompositions for brackets
(U+2329 ≡ U+3008, U+232A ≡ U+3009; UAX #9 BD16 uses canonical equivalence).
Usage: python3 tools/gen_uax9.py
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DATA = os.path.join(ROOT, "tests", "data")
OUT = os.path.join(ROOT, "src", "uax9_tables.rs")
MAX_CP = 0x110000
CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
           "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
IDX = {c: i for i, c in enumerate(CLASSES)}


def main():
    cls = [IDX["L"]] * MAX_CP
    with open(os.path.join(DATA, "DerivedBidiClass.txt"), encoding="utf-8") as f:
        for raw in f:
            if raw.startswith("#") or ";" not in raw:
                continue
            body = raw.split("#", 1)[0]
            rng, val = [c.strip() for c in body.split(";")[:2]]
            lo, hi = (rng.split("..") + [rng])[:2]
            for cp in range(int(lo, 16), int(hi, 16) + 1):
                cls[cp] = IDX[val]
    # Bracket pairs: code point -> (paired code point, type 0=open,1=close), plus canonical singletons.
    brackets = {}
    with open(os.path.join(DATA, "BidiBrackets.txt"), encoding="utf-8") as f:
        for raw in f:
            if raw.startswith("#") or ";" not in raw:
                continue
            fields = [c.strip() for c in raw.split("#", 1)[0].split(";")]
            cp, pair, typ = int(fields[0], 16), int(fields[1], 16), fields[2]
            brackets[cp] = (pair, 0 if typ == "o" else 1)
    canon = {}
    with open(os.path.join(DATA, "UnicodeData.txt"), encoding="utf-8") as f:
        for line in f:
            fs = line.split(";")
            cp = int(fs[0], 16)
            if cp in brackets and fs[5] and not fs[5].startswith("<"):
                parts = fs[5].split()
                if len(parts) == 1:
                    canon[cp] = int(parts[0], 16)
    runs, prev = [], None
    for cp in range(MAX_CP):
        if cls[cp] != prev:
            runs.append((cp, cls[cp]))
            prev = cls[cp]
    with open(OUT, "w", encoding="utf-8") as out:
        out.write("// @generated by tools/gen_uax9.py from tests/data/{DerivedBidiClass,BidiBrackets,UnicodeData}.txt\n")
        out.write("// (Unicode 18.0.0). Do not hand-edit.\n\n")
        out.write("/// Bidi_Class index order (UAX #9 Table 4).\n#[allow(dead_code)]\npub(crate) const CLASS_NAMES: &[&str] = &[\n")
        for c in CLASSES:
            out.write(f'    "{c}",\n')
        out.write("];\n\n")
        out.write(f"/// {len(runs)} runs of Bidi_Class; sorted by start code point.\n")
        out.write("pub(crate) static CLASS_RUNS: &[(u32, u8)] = &[\n")
        for start, v in runs:
            out.write(f"    (0x{start:05X}, {v}),\n")
        out.write("];\n\n")
        out.write("/// Paired brackets (BidiBrackets.txt): (code point, paired code point, is_close).\n")
        out.write("pub(crate) static BRACKETS: &[(u32, u32, bool)] = &[\n")
        for cp in sorted(brackets):
            pair, t = brackets[cp]
            out.write(f"    (0x{cp:04X}, 0x{pair:04X}, {'true' if t == 1 else 'false'}),\n")
        out.write("];\n\n")
        out.write("/// Canonical singleton equivalents of bracket code points (UnicodeData decomposition).\n")
        out.write("pub(crate) static BRACKET_CANON: &[(u32, u32)] = &[\n")
        for cp in sorted(canon):
            out.write(f"    (0x{cp:04X}, 0x{canon[cp]:04X}),\n")
        out.write("];\n")
    print(f"wrote {OUT}: {len(runs)} class runs, {len(brackets)} brackets, {len(canon)} canonical", file=sys.stderr)


if __name__ == "__main__":
    main()
