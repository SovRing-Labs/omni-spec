#!/usr/bin/env python3
"""Black-box oracle for src/otshape.rs: writes tests/data/otshape-oracle.tsv.

Uses HarfBuzz (uharfbuzz, run as a separate process) as the reference shaper. We never read HarfBuzz source;
we only compare its shaping output to ours. Requires: pip install uharfbuzz (any 0.5x wheel).

Rows:
  P <font> <left_gid> <right_gid> <kern_delta>   x_advance change of the first glyph from the 'kern' feature
  L <font> <in_gids,comma> <out_gids,comma>      glyph output of the 'liga' feature

Usage: PYTHONPATH=<site> python3 tools/oracle_otshape.py
"""
import os
import uharfbuzz as hb

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "tests", "data", "otshape-oracle.tsv")
FONTS = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf",
    "/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf",
]
LIGA_STRINGS = ["fi", "fl", "ff", "ffi", "ffl", "ffj", "ft", "st", "AV", "To"]


def shape(font, text, features):
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, features)
    return [(i.codepoint, p.x_advance) for i, p in zip(buf.glyph_infos, buf.glyph_positions)]


def on_offset(font, text, features_on):
    """x_offset of the second glyph with kern on (0 when kern is off)."""
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": features_on, "liga": False})
    return buf.glyph_positions[1].x_offset


def main():
    rows = []
    for path in FONTS:
        name = os.path.basename(path)
        face = hb.Face(hb.Blob.from_file_path(path))
        font = hb.Font(face)
        gid = {c: font.get_nominal_glyph(ord(c)) for c in map(chr, range(0x20, 0x7F))}
        for left in map(chr, range(0x20, 0x7F)):
            for right in map(chr, range(0x20, 0x7F)):
                # Pen position of the glyph after the pair, with and without kern. HarfBuzz may split a pair
                # between x_advance of the first glyph and x_offset of the second, so compare the pen position.
                on = shape(font, left + right, {"kern": True, "liga": False})
                off = shape(font, left + right, {"kern": False, "liga": False})
                delta = (on[0][1] + on_offset(font, left + right, True)) - off[0][1]
                if delta:
                    rows.append(f"P\t{name}\t{gid[left]}\t{gid[right]}\t{delta}")
        for text in LIGA_STRINGS:
            ins = [gid[c] for c in text]
            outs = [g for g, _ in shape(font, text, {"liga": True, "kern": False})]
            rows.append(f"L\t{name}\t{','.join(map(str, ins))}\t{','.join(map(str, outs))}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("# otshape oracle: HarfBuzz %s via uharfbuzz; generated by tools/oracle_otshape.py\n" % hb.version_string())
        f.write("\n".join(rows) + "\n")
    print(f"wrote {OUT}: {len(rows)} rows")


if __name__ == "__main__":
    main()
