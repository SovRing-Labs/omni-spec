#!/usr/bin/env python3
"""Black-box oracle for src/sfnt.rs: writes tests/data/sfnt-oracle.tsv.

Reference: fontTools (table values: head/hhea/maxp/OS-2/name/hmtx) and HarfBuzz via uharfbuzz (cmap lookups,
through hb.Font.get_nominal_glyph). Both run as separate processes; their sources are never read.
Rows:
  F <font> <numGlyphs> <unitsPerEm> <numberOfHMetrics>
  A <font> <gid> <advance> <lsb>              (sampled gids, all for small fonts)
  C <font> <codepoint> <gid>                  (every cmap code point of fontTools' best cmap + unmapped probes)
  N <font> <family name>                      (name ID 1, Windows Unicode preferred)
  O <font> <weight> <typoAsc> <typoDesc> <typoGap> <winAsc> <winDesc>
Usage: PYTHONPATH=<site> python3 tools/oracle_sfnt.py
"""
import os
import random
import uharfbuzz as hb
from fontTools.ttLib import TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "tests", "data", "sfnt-oracle.tsv")
FONTS = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf",
    "/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf",
    "/usr/share/fonts/opentype/urw-base35/C059-Roman.otf",
]


def main():
    rows = []
    for path in FONTS:
        name = os.path.basename(path)
        tt = TTFont(path)
        head, hhea, maxp = tt["head"], tt["hhea"], tt["maxp"]
        rows.append(f"F\t{name}\t{maxp.numGlyphs}\t{head.unitsPerEm}\t{hhea.numberOfHMetrics}")
        hmtx = tt["hmtx"].metrics
        order = tt.getGlyphOrder()
        for gid in range(maxp.numGlyphs):
            gname = order[gid] if gid < len(order) else None
            adv, lsb = hmtx.get(gname, (0, 0)) if gname else (0, 0)
            rows.append(f"A\t{name}\t{gid}\t{adv}\t{lsb}")
        cmap = tt.getBestCmap() or {}
        probes = list(cmap.keys()) + random.Random(3).sample(range(0x20, 0x3000), 200)
        blob = hb.Blob.from_file_path(path)
        font = hb.Font(hb.Face(blob))
        for cp in sorted(set(probes)):
            rows.append(f"C\t{name}\t{cp}\t{font.get_nominal_glyph(cp) or 0}")
        family = None
        for rec in tt["name"].names:
            if rec.nameID == 1 and rec.platformID == 3:
                family = rec.toUnicode()
                break
        if family is None:
            family = tt["name"].getDebugName(1) or ""
        rows.append(f"N\t{name}\t{family}")
        o = tt["OS/2"]
        rows.append(f"O\t{name}\t{o.usWeightClass}\t{o.sTypoAscender}\t{o.sTypoDescender}\t{o.sTypoLineGap}\t{o.usWinAscent}\t{o.usWinDescent}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("# sfnt oracle: fontTools + HarfBuzz (uharfbuzz); generated by tools/oracle_sfnt.py\n")
        f.write("\n".join(rows) + "\n")
    print(f"wrote {OUT}: {len(rows)} rows")


if __name__ == "__main__":
    main()
